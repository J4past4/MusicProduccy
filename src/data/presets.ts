/**
 * Smart UK Bassline Patch Mutator:
 * Generates musical, club-ready 140 BPM bassline variations without breaking gain/sub stability.
 */
export function mutateBassPatch(base: SubtractorPatch): SubtractorPatch {
  const pick = <T,>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)];
  const rand = (min: number, max: number) => min + Math.random() * (max - min);

  const bassWaves1 = [1, 2, 3, 4, 5, 9, 10, 11, 12, 13, 14, 19, 21, 30];
  const bassWaves2 = [1, 2, 3, 4, 10, 11, 12, 29, 30, 31];
  const f1Types: SubtractorPatch['filter1Type'][] = ['lp24', 'lp12', 'bp12', 'notch'];
  const lfoSyncIndexes = [7, 8, 9, 10, 11, 13]; // 1/4, 1/4T, 1/8D, 1/8, 1/8T, 1/16
  const phaseModes: SubtractorPatch['osc1PhaseMode'][] = ['off', 'subtract', 'multiply'];

  const f1Type = pick(f1Types);
  const useWobble = Math.random() > 0.42;

  return {
    ...base,
    id: `mutated-${Date.now()}`,
    name: `UK Mutate #${Math.floor(100 + Math.random() * 900)}`,
    category: useWobble ? 'Wobble' : 'Warp',
    artistRef: 'SUBTRAKTOR-140 Generator',
    polyphony: 1,
    playMode: Math.random() > 0.4 ? 'legato' : 'retrig',
    portamento: Math.random() > 0.4 ? rand(0.08, 0.28) : 0,
    osc1Wave: pick(bassWaves1),
    osc1PhaseMode: pick(phaseModes),
    osc1Phase: rand(0.15, 0.65),
    osc1Octave: 3,
    osc2On: true,
    osc2Wave: pick(bassWaves2),
    osc2PhaseMode: Math.random() > 0.5 ? pick(phaseModes) : 'off',
    osc2Phase: rand(0.1, 0.6),
    osc2Octave: pick([3, 4, 5]),
    osc2Semi: pick([0, 0, 0, 7, 12]),
    oscMix: rand(0.04, 0.42),
    fmAmount: rand(0.12, 0.52),
    ringMod: Math.random() < 0.14,
    filter1Type: f1Type,
    filter1Freq: rand(0.2, 0.48),
    filter1Res: rand(0.28, 0.72),
    filter2On: f1Type === 'bp12' || f1Type === 'notch' || Math.random() > 0.5,
    filterLink: true,
    filter2Freq: rand(0.45, 0.72),
    filter2Res: rand(0.12, 0.35),
    filterEnvAttack: useWobble ? rand(0.01, 0.12) : rand(0.01, 0.32),
    filterEnvDecay: rand(0.18, 0.42),
    filterEnvSustain: rand(0.05, 0.25),
    filterEnvAmount: rand(0.35, 0.78),
    filterEnvInvert: Math.random() < 0.18,
    modEnvAttack: rand(0.01, 0.26),
    modEnvDecay: rand(0.14, 0.36),
    modEnvSustain: rand(0, 0.15),
    modEnvAmount: rand(0.25, 0.72),
    modEnvDest: pick(['fm', 'phase', 'freq2', 'osc2']),
    lfo1Wave: pick(['triangle', 'rampDown', 'rampUp', 'square']),
    lfo1Dest: pick(['filterFreq', 'fm', 'phase']),
    lfo1Sync: true,
    lfo1Rate: pick(lfoSyncIndexes) / 15,
    lfo1Amount: useWobble ? rand(0.32, 0.68) : rand(0, 0.22),
    fxSubOn: true,
    fxSubLevel: rand(0.45, 0.68),
    fxDriveOn: true,
    fxDriveType: pick(['tube', 'tape', 'fold']),
    fxDriveAmount: rand(0.18, 0.45),
    fxSidechainAmount: rand(0.25, 0.45),
  };
}
